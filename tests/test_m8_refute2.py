class MeasurementTests(Base, unittest.TestCase):
    """F7 (a probe in the report): the supervisor's own measurements renew the claim and count in the deadline."""
    timeout = 300  # the check limits cover the replaced clock's jumps below; the 60-second lease does not

    def test_f7_a_measurement_longer_than_the_lease_keeps_the_claim(self):
        # Injected: every declared file takes some seconds of the replaced clock to read, so one
        # measurement is longer than the lease (the report measured 5 ms per file on Windows:
        # 12000 files are 60 seconds).
        plan = self.repo.plan(b'synthetic pass\n')
        files = sum(1 for entry in plan['source']['inputs'] if entry['kind'] == 'file')
        step = math.ceil(61 / files)
        space, clock = self.space(), Clock()
        measuring = []
        original_read, original_run = snapshot_module._SnapshotReader.read, execute_module._Supervisor.run

        def read_slowly(reader, path):
            if measuring:
                clock.advance(step)
                time.sleep(0.03)  # longer than the heartbeat interval of this run
            return original_read(reader, path)

        def run(supervisor, index, check):
            outcome = original_run(supervisor, index, check)
            measuring.append(index)
            return outcome
        with patch.object(snapshot_module._SnapshotReader, 'read', read_slowly), \
                patch.object(execute_module._Supervisor, 'run', run):
            verdict, _, space = self.run_plan(plan, space=space, clock=clock, heartbeat_seconds=0.02)
        self.assertGreater(step * files, 60)
        self.assertEqual(verdict, {'status': 'accepted', 'exitCode': 0},
                         'one measurement of %d files took %d s of the clock' % (files, step * files))
        self.assertEqual(len(measuring), len(plan['checks']))
        self.assertEqual(self.types(space)[-1], 'claim-closed')

    def test_a_slow_renewal_is_not_repeated_at_every_file(self):
        # Added by the integrating session: after a journal with a receipt of 10000 artifacts,
        # one journal operation took 14.6 s here, longer than the 10-second interval. The next
        # renewal is due one interval after the last one ended, not at the next file read.
        plan = self.repo.plan(b'synthetic pass\n')
        files = sum(1 for entry in plan['source']['inputs'] if entry['kind'] == 'file')
        self.assertGreater(files, 2)
        original_beat, original_digest = claim_module.heartbeat, snapshot_module.digest_after
        measuring, inside = [], []

        def beat(*args, **kwargs):
            time.sleep(0.3)  # longer than the interval of this run
            if measuring:
                inside.append(1)
            return original_beat(*args, **kwargs)

        def digest(*args, **kwargs):
            measuring.append(1)
            try:
                return original_digest(*args, **kwargs)
            finally:
                measuring.pop()
        with patch.object(claim_module, 'heartbeat', beat), patch.object(snapshot_module, 'digest_after', digest):
            verdict, _, _ = self.run_plan(plan, heartbeat_seconds=0.2)
        self.assertEqual(verdict, {'status': 'accepted', 'exitCode': 0})
        # At most one renewal per measurement (one after each check), never one per file.
        self.assertLessEqual(len(inside), len(plan['checks']))

    def test_f7_the_deadline_allows_one_measurement_after_each_check(self):
        plan = self.repo.plan(b'synthetic pass\n')
        verdict, out, _ = self.run_plan(plan)
        self.assertEqual(verdict, {'status': 'accepted', 'exitCode': 0})
        execution = read(out, 'execution.json')
        files = sum(1 for entry in plan['source']['inputs'] if entry['kind'] == 'file')
        checks = plan['checks']
        expected = (sum(check['timeoutSeconds'] + 5 for check in checks)
                    + math.ceil(0.02 * files * len(checks)) + 30)
        started, deadline = (datetime.strptime(execution[name], '%Y-%m-%dT%H:%M:%SZ')
                             for name in ('startedAt', 'deadlineAt'))
        self.assertEqual((deadline - started).total_seconds(), expected)


