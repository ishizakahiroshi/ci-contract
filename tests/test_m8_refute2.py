class LongPathRepository:
    """A synthetic repository with one declared file whose private copy exceeds MAX_PATH on Windows."""
    LONG = 'src/' + 'd' * 120 + '/' + 'e' * 120 + '/long.txt'

    def __init__(self, root):
        manifest = execute_manifest(*IDENTITY, adapter=ADAPTER)
        rules = manifest['selectionModel']['inputRules']
        extra = next(rule for rule in rules if rule['path'] == EXTRA_PATH)
        rules.append(dict(extra, id='synthetic-rule-long', path=self.LONG))
        self.git, self.base, self.files = execute_history(Path(root) / 'long.git', manifest, adapter=ADAPTER)

    def plan(self):
        files = target_files(self.files, b'synthetic pass\n')
        files[self.LONG] = ('100644', b'synthetic long path\n')
        target = self.git.commit(files, parents=(self.base,), message='synthetic target')
        return build_plan(self.git.path, 'synthetic', self.base, target)


