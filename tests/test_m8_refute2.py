def read(out, name):
    return cjson.loads((Path(out) / name).read_bytes())


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def utc(moment):
    return moment.strftime('%Y-%m-%dT%H:%M:%SZ')


def other_binding(plan, space, clock, request_id='synthetic-other-request'):
    return make_request_binding(plan, request_id=request_id, authority_id=space.anchored.authority_id,
                                target='local', trust='trusted', workflow_commit=None, created_at=utc(clock.now),
                                expires_at=utc(clock.now + timedelta(hours=1)),
                                authority_kind='local-single-supervisor-v1')


def seen_payload(out, index, logical):
    text = (Path(out) / 'logs' / ('%02d-%s.log' % (index, logical))).read_text(encoding='utf-8')
    return text.split('seen-payload ', 1)[1].split()[0]


class GeneratedInputTests(Base, unittest.TestCase):
    """F1: a dependent check's generated input is measured once, after its producer, never again."""
    generation = True

    def order(self, plan):
        return [check['logicalCheckId'] for check in execute_module._order(plan['checks'])]

    def test_sound_baseline_generation_is_accepted_and_the_dependent_reads_the_payload(self):
        plan = self.repo.plan(b'synthetic pass\n')
        order = self.order(plan)
        verdict, out, _ = self.run_plan(plan)
        self.assertEqual(verdict, {'status': 'accepted', 'exitCode': 0})
        self.assertEqual(seen_payload(out, order.index('app.test'), 'app.test'), sha256(b'synthetic payload\n'))

    def test_f1_a_dependent_check_reads_other_generated_bytes_than_its_proof_names(self):
        probe = self.repo.plan(b'synthetic probe\n')
        order = self.order(probe)
        between = order[order.index('app.generate') + 1:order.index('app.test')]
        self.assertTrue(between, 'no check runs between app.generate and app.test: %s' % order)
        # A check between producer and dependent writes the same build output path (an accident
        # of two build steps), after the supervisor measured the producer's payload.
        plan = self.repo.plan(('overwrite %s forged payload\n' % between[0]).encode())
        self.assertEqual(self.order(plan), order)
        verdict, out, space = self.run_plan(plan)
        if verdict['exitCode'] != 0:
            # The fixed behaviour: the dependent does not start with other generated bytes.
            self.assertEqual(verdict, {'status': 'unknown', 'exitCode': 8})
            events = json.loads((Path(out) / 'events.json').read_bytes())
            self.assertIn({'event': 'generated-input-changed'},
                          [event for logged in events.values() for event in logged])
            self.assertFalse((Path(out) / 'logs' / ('%02d-app.test.log' % order.index('app.test'))).exists())
            self.assertEqual(self.types(space)[-1], 'claim-closed')
            return
        result = read(out, 'result.json')
        proofs = {receipt['proof']['identity']['logicalCheckId']: receipt['proof'] for receipt in result['checks']}
        named = proofs['app.test']['identity']['generatedInputDigests']
        seen = seen_payload(out, order.index('app.test'), 'app.test')
        self.assertEqual(named, [sha256(b'synthetic payload\n')])
        self.assertEqual(seen, sha256(b'forged payload\n'))
        self.assertEqual((Path(out) / 'artifacts' / 'synthetic-payload').read_bytes(), b'synthetic payload\n')
        self.fail('accepted although app.test read %s while its proof names %s as its generated input '
                  '(the receipt folder keeps the producer\'s bytes; journal ends %s)'
                  % (seen[:12], named[0][:12], self.types(space)[-1]))


